"""Writes qr_repo.scad: the QR code on the case bottom as a 0/1 matrix (1 = dark module), no quiet zone.

Run after changing URL: uv run --no-project --with qrcode python make_qr.py
"""
import pathlib

import qrcode

URL = "https://github.com/fhirschmann/halo2-controller"   # repo not created yet (2026-10-28)

qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=0)
qr.add_data(URL)
qr.make(fit=True)
rows = qr.get_matrix()
out = pathlib.Path(__file__).with_name("qr_repo.scad")
out.write_text(
    f"// Generated by make_qr.py, do not edit: QR version {qr.version}, error correction M, {len(rows)} x {len(rows)}\n"
    f'qr_url = "{URL}";\n'
    "qr_matrix = [\n" + ",\n".join("    [" + ", ".join("1" if v else "0" for v in r) + "]" for r in rows) + "\n];\n")
print(f"{out.name}: version {qr.version}, {len(rows)} modules")
